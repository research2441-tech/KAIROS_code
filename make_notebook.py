"""Generates KAIROS_Colab.ipynb: every source file is written by a %%writefile cell, followed by run cells."""
import nbformat as nbf

FILES = ["common.py", "synth.py", "prep.py", "kairos.py", "plans.py", "run_exp.py", "analyze.py", "flops.py",
         "fig_arch.py", "fig_sampler.py", "fig_tokens.py", "figs_results.py", "fig_extra.py", "merge_chunks.py"]
nb = nbf.v4.new_notebook()
C = []
md = lambda s: C.append(nbf.v4.new_markdown_cell(s))
code = lambda s: C.append(nbf.v4.new_code_cell(s))

md("""# KAIROS: velocity-proportional frame and token allocation for long-form action recognition

This notebook reproduces every number, table and figure of the manuscript on a free Google Colab instance.

**Pipeline**
1. write the source files (one `%%writefile` cell per module);
2. download HMDB51 (split 1) and the openly redistributable Something-Something V2 evaluation subset from the Hugging Face Hub, and generate the TRACE-10 benchmark locally;
3. run the camera-compensated pixel probe on every raw frame and encode a uniform candidate lattice with a frozen DINOv2 ViT-S/14 (GPU if available);
4. train all compared methods, ablations and sensitivity runs (three seeds for the main study);
5. aggregate statistics and draw the figures.

**Runtime (free Colab, T4 GPU).** Feature extraction takes roughly 25–40 minutes; the full experiment plan takes roughly 1–2 hours. Set `QUICK = True` below to run one seed of the main comparison only.

`Runtime > Change runtime type > T4 GPU` is recommended but not required.""")
code("""QUICK = False          # True: one seed of the main comparison only
N_WORKERS = 2          # parallel training processes""")
code("""!pip -q install timm av opencv-python-headless pyarrow scipy nbformat
import torch, platform; print(torch.__version__, platform.python_version(), 'cuda' if torch.cuda.is_available() else 'cpu')""")
for f in FILES:
    md(f"### `{f}`")
    code(f"%%writefile {f}\n" + open(f).read())
md("## 1. Data\nHMDB51 split 1 and the SSv2 evaluation subset are distributed as parquet files on the Hugging Face Hub (`mteb/HMDB51`, `mteb/SomethingSomethingV2`). TRACE-10 is generated by `synth.py`.")
code("""%%bash
mkdir -p raw/hmdb raw/ssv2 figs results
B=https://huggingface.co/datasets
for f in train-00000-of-00003 train-00001-of-00003 train-00002-of-00003 test-00000-of-00001; do
  [ -f raw/hmdb/$f.parquet ] || curl -sL -o raw/hmdb/$f.parquet $B/mteb/HMDB51/resolve/main/data/$f.parquet
done
[ -f raw/ssv2/test-00000-of-00001.parquet ] || curl -sL -o raw/ssv2/test-00000-of-00001.parquet $B/mteb/SomethingSomethingV2/resolve/main/data/test-00000-of-00001.parquet
ls -la raw/*""")
md("## 2. Probe and frozen-encoder features\nEach command decodes every clip once, runs the probe on all raw frames and encodes the candidate lattice. Tokens are reduced to 192 dimensions with a PCA fitted on training clips only.")
code("""!python prep.py trace
!python prep.py hmdb
!python prep.py ssv2""")
md("## 3. Experiments\n`main`: 12 methods × 3 datasets × 3 seeds with stress tests; `abl`: factorial ablation and component removals; `sens`: sensitivity sweeps. Runs are resumable: finished runs are skipped.")
code("""import subprocess, sys
def run(plan):
    ps = [subprocess.Popen([sys.executable, 'run_exp.py', plan, str(w), str(N_WORKERS)]) for w in range(N_WORKERS)]
    for p in ps: p.wait()
if QUICK:
    import plans
    plans.PLANS['quick'] = lambda: plans._jobs(plans.MAIN, plans.DS, [0], extra=True)
    open('plans.py','a').write("\\nPLANS['quick'] = lambda: _jobs(MAIN, DS, [0], extra=True)\\n")
    run('quick')
else:
    for plan in ['main', 'abl', 'sens']:
        run(plan)""")
md("## 4. Statistics, cost and figures")
code("""!python flops.py > /dev/null
!python analyze.py
!python fig_arch.py && python fig_sampler.py && python fig_tokens.py && python figs_results.py && python fig_extra.py""")
code("""import json
S = json.load(open('results/summary.json'))
for ds in S['runs']:
    print(f'== {ds}')
    for n, r in S['runs'][ds].items():
        if n in ['TSN-mean','Uniform-CLS','Dense-CLS','Uniform-Full','MG-Full','Uniform-Random','Uniform-STTS','Uniform-ToMe','Uniform-EViT','Uniform-RLT','MG-STTS','Ours']:
            print(f"{n:16s} top-1 {100*r['test'][0]:6.2f} ± {100*r['test'][1]:.2f}   ECE {100*r['ece'][0]:.2f}")
print(json.dumps(S.get('friedman', {}), indent=1)[:800])""")
